/// A test file left out of the list above would never be built or run, and nothing would
/// say so.
#[test]
fn every_test_file_is_listed() {
    let here = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests");
    let listed = include_str!("main.rs");
    let missing: Vec<String> = std::fs::read_dir(&here).unwrap().flatten()
        .filter_map(|e| e.file_name().to_str().and_then(|n| n.strip_suffix(".rs")).map(str::to_string))
        .filter(|n| n != "main" && !listed.contains(&format!("\nmod {n};\n")))
        .collect();
    assert!(missing.is_empty(), "not in tests/main.rs, so never run: {missing:?}");
}
